/** Newest-first, id as a stable tiebreaker — mirrors build-worker.ts's own sort so an ejected build routes/paginates posts identically to the hosted one. */
function sortPostsNewestFirst(posts: PostDocument[]): PostDocument[] {
  return [...posts].sort((a, b) => (a.date === b.date ? (a.id < b.id ? 1 : -1) : a.date < b.date ? 1 : -1));
}

/**
 * Export tier (c) (ADR-0010): generates a standalone Astro project from a
 * document tree. Reuses `SITE_PAGE_ASTRO` verbatim — the exact same page
 * template the hosted publish pipeline builds with (build-worker.ts) — so
 * fidelity (R9) is a property of sharing one template, not of two
 * templates being kept in sync by hand.
 */
export async function ejectSite(input: EjectSiteInput): Promise<EjectResult> {
  const { outDir } = input;
  await mkdir(outDir, { recursive: true });

  await cp(BLOCKS_SRC_ROOT, path.join(outDir, "src", "blocks"), { recursive: true });

  const schemaShimDir = path.join(outDir, "src", "prefab-schema");
  await mkdir(schemaShimDir, { recursive: true });
  await writeFile(path.join(schemaShimDir, "index.mjs"), prefabSchemaShimSource(), "utf8");
  await writeFile(path.join(schemaShimDir, "index.d.ts"), prefabSchemaShimTypesSource(), "utf8");

  const pagesDir = path.join(outDir, "src", "pages");
  await mkdir(pagesDir, { recursive: true });
  await writeFile(path.join(pagesDir, "[...slug].astro"), SITE_PAGE_ASTRO, "utf8");

  const data = {
    site: input.site,
    theme: input.theme,
    pages: input.pages,
    posts: sortPostsNewestFirst(input.posts ?? []),
    runtimeApiUrl: input.runtimeApiUrl ?? "",
    turnstileSiteKey: input.turnstileSiteKey ?? "",
  };
  await writeFile(path.join(outDir, "src", "data.json"), JSON.stringify(data), "utf8");

  await writeFile(path.join(outDir, "astro.config.mjs"), astroConfigSource(), "utf8");
  await writeFile(path.join(outDir, "package.json"), packageJsonSource(input.site.slug), "utf8");
  await writeFile(path.join(outDir, "tsconfig.json"), tsconfigSource(), "utf8");
  await writeFile(path.join(outDir, "README.md"), readmeSource(input.site.slug), "utf8");
  await writeFile(path.join(outDir, ".gitignore"), "node_modules/\ndist/\n.astro/\n", "utf8");

  return { outDir };
}

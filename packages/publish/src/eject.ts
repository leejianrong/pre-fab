import { cp, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  BREAKPOINTS,
  BREAKPOINT_MIN_WIDTH,
  DEFAULT_THEME_TOKENS,
  type PageDocument,
  type PostDocument,
  type SiteManifest,
  type ThemeDocument,
} from "@prefab/schema";
import { SITE_PAGE_ASTRO } from "./page-template.js";

const PACKAGE_ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
/** @prefab/blocks is a sibling workspace package — see this file's module comment for why its source is copied wholesale rather than depended on. */
const BLOCKS_SRC_ROOT = path.join(PACKAGE_ROOT, "..", "blocks", "src");

// Pinned to exactly what packages/publish's own hosted pipeline builds
// against (see this package's package.json) — R9's pixel-fidelity claim
// requires the ejected project to render with the identical Astro/React
// versions, not just the identical component source.
const ASTRO_VERSION = "7.2.8";
const ASTROJS_REACT_VERSION = "6.0.4";
const REACT_VERSION = "19.0.0";
const ZOD_VERSION = "4.4.3";

export interface EjectSiteInput {
  site: SiteManifest;
  theme: ThemeDocument;
  pages: PageDocument[];
  posts?: PostDocument[];
  runtimeApiUrl?: string;
  turnstileSiteKey?: string;
  outDir: string;
}

export interface EjectResult {
  outDir: string;
}

function prefabSchemaShimSource(): string {
  return `// Generated by \`prefab eject\` (Slice 7, ADR-0010 tier c) — do not import
// this from anything other than the alias below. It vendors the tiny
// handful of @prefab/schema exports @prefab/blocks' components actually
// touch at runtime; everything else a block imports from "@prefab/schema"
// is \`import type\`, erased entirely at build time, so it never needs a
// real module here at all. Aliased to the "@prefab/schema" bare specifier
// in astro.config.mjs, which is what lets every file under src/blocks be a
// byte-for-byte copy of this site's own block library — nothing to
// rewrite, nothing to risk diverging (R9's pixel-fidelity claim).
export const BREAKPOINTS = ${JSON.stringify(BREAKPOINTS)};
export const BREAKPOINT_MIN_WIDTH = ${JSON.stringify(BREAKPOINT_MIN_WIDTH)};

export function isUlid(value) {
  return typeof value === "string" && /^[0-9A-HJKMNP-TV-Z]{26}$/.test(value);
}

export const DEFAULT_THEME_TOKENS = ${JSON.stringify(DEFAULT_THEME_TOKENS, null, 2)};

export class BlockRegistry {
  #definitions = new Map();
  register(definition) {
    this.#definitions.set(definition.type, definition);
    return this;
  }
  get(type) {
    return this.#definitions.get(type);
  }
  has(type) {
    return this.#definitions.has(type);
  }
  types() {
    return [...this.#definitions.keys()];
  }
}
`;
}

